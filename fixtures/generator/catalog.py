"""The golden set — one spec per canonical test case, with expected verdicts.

Tier A of the two-tier set: synthetic, deterministic, regenerable, and the
tier that gates CI. Tier B is real bottle photographs, reported separately and never
gating, because a set generated by our own renderer only proves the pipeline can read our
own renderer.

Every spec here names the TC it covers. A TC with no spec is a hole in the golden set.

**Read this before adding a knob to `LabelSpec` or editing a warning fixture.**

This file has been attacked four times, and each time one line in it switched off the
zero-false-pass gate while the report printed a confident number and the whole test suite
stayed green. The pins below are shaped by those four findings, and they are worth
understanding before you work around one:

1. **A marker.** `pending="LP-nnn"` dropped a fixture out of both the numerator and the
   denominator, so a live false pass reported as `0 false passes`.
   Answer: `pending` excuses an inaccurate verdict, never a passing one.
2. **A declared expectation.** `expect={}` made the row expect a clean Match, so it stopped
   being a violation at all — it did not fail the gate, it left it.
   Answer: `MUST_DECLARE_WARNING_VIOLATION`, and the pin outranks `expect`.
3. **A rendered defect.** Adding `warning_header_case="title"` to the prominence fixture
   made the pipeline answer `mismatch` for an unrelated reason, satisfying the
   expectation while the violation under test stayed undetected.
   Answer: `WARNING_DEFECT_PINS`, exact sets in both directions.
4. **A type.** `warning_body_bold=None` drew byte-identical pixels — the renderer reads it
   as falsy — while the extractor reported the tri-state "could not determine", which made
   the verdict non-passing for, again, an unrelated reason.
   Answer: identity tests instead of truthiness, plus `spec_type_problems`.

The pattern: each door was a layer deeper than the last, and each was found by someone
attacking the gate rather than confirming it. Three of the four were invisible to the
whole test suite. If you add a knob here, assume it is door five until you have tried to
open it — and prefer a pin that describes *what the fixture draws* over one that describes
a declaration about it.
"""

