#: Fixtures that MUST be scored as government-warning violations on every full run.
#:
#: The zero-false-pass gate's denominator, pinned in the repository. Without this, marking
#: a fixture `pending` silently drops a check and the report still says "0 false passes",
#: just across a smaller set — the cheapest way there is to clear a red build. Shrinking
#: the gate now means shrinking this list, which is a line in a diff someone has to
#: approve. Growing it is free and encouraged.
#:
#: `tc06_buried_warning` is deliberately absent: it is pending LP-211 and currently
#: produces a live false pass (see the eval report). It joins this list when prominence
#: heuristics land and it stops passing.
REQUIRED_WARNING_VIOLATIONS: frozenset[str] = frozenset(
    {
        "tc03_title_case_warning",
        "tc04_bold_warning_body",
        "tc05_reworded_warning",
        "tc07_missing_warning",
    }
)


#: Fixtures whose `expect` MUST declare a government-warning violation.
#:
#: A superset of REQUIRED_WARNING_VIOLATIONS, and the reason it exists is that hardening
#: `pending` left `expect` — one line above it — doing exactly the same job. Deleting
#: `expect={"government_warning": "mismatch"}` makes the row expect a clean Match, so it
#: stops being a declared violation, disappears from the report entirely, and the run
#: prints "0 false passes across 4 violation row(s)" and exits 0. It is a two-line diff
#: that any author revisiting an expectation might make in good faith.
#:
#: `tc06_buried_warning` IS in this list even though it is absent from
#: REQUIRED_WARNING_VIOLATIONS. That asymmetry is the whole point: the one fixture whose
#: expectation is under active discussion is the one the scoring pin cannot cover, because
#: it is `pending`. This list covers it at the declaration level instead. Its expectation
#: may legitimately change (LP-211 moves it from `mismatch` to `unreadable` — still a
#: violation, still non-passing); what it may not do is quietly become no expectation.
MUST_DECLARE_WARNING_VIOLATION: frozenset[str] = REQUIRED_WARNING_VIOLATIONS | {
    "tc06_buried_warning",
}


# --------------------------------------------------------------------------------------
# What a fixture RENDERS — the defect it embodies, not a declaration about it
# --------------------------------------------------------------------------------------
#
# Three reviews found three doors into the zero-false-pass gate, each one line:
# `pending` suppressed the false pass, `expect` removed the declaration, and then simply
# drawing a *different* defect made the pipeline answer `mismatch` — which satisfied the
# expectation, so nothing fired, while the violation the fixture existed to catch went
# right on being undetected.
#
# The pattern was that every pin protected a DECLARATION ABOUT the fixture. These pin the
# DEFECT ITSELF. A fixture whose whole job is to prove that a buried warning is caught has
# to keep burying the warning, and has to keep doing only that: swapping the prominence
# knobs for a title-case header turns a hard case into an easy one that the rules engine
# already catches, and the swap reads like a routine retarget in a diff.

#: Scale below which the warning counts as rendered too small to be prominent (WARN-5).
PROMINENCE_SCALE_CEILING = 0.6

#: Contrast below which the warning counts as rendered too faint (WARN-5).
PROMINENCE_CONTRAST_CEILING = 0.5


#: Rendering knobs that must be a real `bool`. They are typed `bool` on `LabelSpec`, but
#: `with_` funnels through `**changes: object`, so nothing stops `None` being set — and
#: `None` is a tri-state on the *other* side of this boundary, where it means "the
#: extractor could not tell". That mismatch was door four; see the module docstring.
BOOL_RENDER_KNOBS: tuple[str, ...] = (
    "include_warning",
    "warning_header_bold",
    "warning_body_bold",
)

#: Rendering knobs that must be a real number.
NUMERIC_RENDER_KNOBS: tuple[str, ...] = ("warning_scale", "warning_contrast")


def spec_type_problems(spec: LabelSpec) -> list[str]:
    """Rendering knobs holding something the renderer cannot mean."""
    problems = []
    for knob in BOOL_RENDER_KNOBS:
        value = getattr(spec, knob)
        if not isinstance(value, bool):
            problems.append(
                f"{spec.name}: {knob}={value!r} is not a bool. This knob describes what is "
                f"DRAWN, where there is no 'unknown' — the renderer treats None as False "
                f"and draws a clean label, while the extractor reports a tri-state "
                f"'could not determine'. Those are different claims."
            )
    for knob in NUMERIC_RENDER_KNOBS:
        value = getattr(spec, knob)
        if isinstance(value, bool) or not isinstance(value, int | float):
            problems.append(f"{spec.name}: {knob}={value!r} is not a number")
    return problems


def warning_defects(spec: LabelSpec) -> frozenset[str]:
    """Exactly which 27 CFR 16.21/16.22 defects this spec DRAWS.

    Derived from the render parameters, so it describes pixels rather than intent. A spec
    with no defects returns the empty set.

    **Every bool test here is identity, never truthiness.** A truthiness test on a knob
    that is a tri-state one layer down is precisely how door four opened: `if
    spec.warning_body_bold:` read `None` as "no defect", the pin stayed satisfied, and the
    fixture kept drawing byte-identical pixels while the extractor started reporting
    "could not determine" — which made the verdict non-passing for an unrelated reason and
    took the run from exit 3 to exit 0. `is not False` says what is meant: the pin needs
    this body to be *definitely* not bold, and `None` is not definitely anything.
    """
    if spec.include_warning is not True:
        return frozenset({"absent"})

    defects: set[str] = set()
    if spec.warning_header_case != "upper":
        defects.add("header_not_all_caps")
    if spec.warning_header_bold is not True:
        defects.add("header_not_bold")
    if spec.warning_body_bold is not False:
        defects.add("body_bold")
    if spec.warning_text is not None:
        defects.add("text_altered")
    if (
        spec.warning_scale < PROMINENCE_SCALE_CEILING
        or spec.warning_contrast < PROMINENCE_CONTRAST_CEILING
    ):
        defects.add("prominence")
    return frozenset(defects)


#: fixture name -> the EXACT defect set it must render. Equality, not containment.
#:
#: Exact, because both directions are attacks. Removing the pinned defect stops the
#: fixture testing anything; adding another one lets an easy defect stand in for a hard
#: one, and the report still shows a green row. `tc06_buried_warning` is the case that
#: matters most: prominence heuristics do not exist yet (LP-211), so it is the one fixture
#: whose expectation is under discussion, and adding `warning_header_case="title"` to it
#: made the pipeline answer `mismatch`, satisfy the expectation, and exit 0.
WARNING_DEFECT_PINS: dict[str, frozenset[str]] = {
    "tc03_title_case_warning": frozenset({"header_not_all_caps"}),
    "tc04_bold_warning_body": frozenset({"body_bold"}),
    "tc05_reworded_warning": frozenset({"text_altered"}),
    "tc06_buried_warning": frozenset({"prominence"}),
    "tc07_missing_warning": frozenset({"absent"}),
}


def misrendered_warning_fixtures(specs: list[LabelSpec]) -> list[str]:
    """Pinned fixtures that no longer draw exactly the defect they were pinned to draw.

    Reported as `name: drew {...}, pinned {...}` so the diff is legible without opening
    the catalog. A knob holding a value the renderer cannot mean is reported here too:
    the fixture is not drawing what it claims either way, and one gate is easier to trust
    than two.
    """
    present = {spec.name: spec for spec in specs}
    wrong = []
    for spec in specs:
        wrong.extend(spec_type_problems(spec))
    for name in sorted(WARNING_DEFECT_PINS.keys() & present.keys()):
        drew = warning_defects(present[name])
        pinned = WARNING_DEFECT_PINS[name]
        if drew != pinned:
            wrong.append(
                f"{name}: draws {sorted(drew) or 'no defect'}, pinned {sorted(pinned)}"
            )
    return wrong


def declares_warning_violation(spec: LabelSpec) -> bool:
    """Does this spec's `expect` say the warning must NOT pass?"""
    expected = spec.expect.get("government_warning")
    return expected is not None and expected not in ("match", "not_applicable")


def undeclared_warning_violations(specs: list[LabelSpec]) -> list[str]:
    """Fixtures the repository requires to declare a violation, that no longer do.

    Only fixtures actually present in `specs` are checked, so a `--fixture` subset run
    does not report every absent name as a defect.
    """
    present = {spec.name: spec for spec in specs}
    return sorted(
        name
        for name in MUST_DECLARE_WARNING_VIOLATION & present.keys()
        if not declares_warning_violation(present[name])
    )


def by_name(name: str) -> LabelSpec:
    for spec in CATALOG:
        if spec.name == name:
            return spec
    raise KeyError(f"no fixture named {name!r}")
