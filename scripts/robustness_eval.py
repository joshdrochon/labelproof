"""Per-condition robustness report (LP-199, OPS-2).

`eval/run.py` answers "how accurate is the pipeline on a clean label". This answers the
question underneath it: **which conditions is it accurate under**, one row per degradation.
An aggregate that says 96% hides whether the missing 4% is spread evenly or is entirely
"every photograph taken at an angle".

Each condition in `fixtures.generator.degrade` declares what the pipeline owes it —
readable, warning_illegible, or pregated — and this checks that exact obligation and
reports two numbers that must never be confused:

* **false pass** — something illegible was treated as legible. A field verified from
  pixels nobody could read. This is the failure that matters; it is silent, and the
  output looks identical to a correct one.
* **false flag** — something legible was treated as illegible. Annoying, costs an agent a
  retake request they did not need, and is not in the same category.

**A change that reduces flags by increasing false passes is a regression.** The report
prints both so that trade cannot be made by accident.

    python -m scripts.robustness_eval
    python -m scripts.robustness_eval --json
    python -m scripts.robustness_eval --photos fixtures/photos     # Tier B

Tier A and Tier B are never averaged. A set generated by our own renderer only proves the
pipeline can read our own renderer, and blending the two would hide the number that
matters (BUILD.md §5).
"""

from __future__ import annotations

import argparse
import json
import sys
