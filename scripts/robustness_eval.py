def evaluate_photos(directory: Path) -> Report:
    """Score real photographs against a hand-written expectation file.

    Expectations live in `expectations.json` beside the images, mapping each filename to
    one of the same three obligations. Without that file the run reports measurements and
    claims no accuracy — a number computed against ground truth nobody wrote down is not
    a number.
    """
    from PIL import Image

    report = Report(tier="B")
    expectations: dict[str, str] = {}
    manifest = directory / "expectations.json"
    if manifest.exists():
        expectations = json.loads(manifest.read_text())

    for path in sorted(directory.iterdir()):
        if path.suffix.lower() not in (".jpg", ".jpeg", ".png", ".heic", ".webp"):
            continue
        with Image.open(path) as opened:
            image = np.array(opened.convert("RGB"))

        processed = preprocess.preprocess(image)
        pregated = quality.should_skip_extraction(processed.quality_before)
        report.outcomes.append(
            Outcome(
                condition=path.name,
                tc="Tier B",
                expectation=expectations.get(path.name, "unstated"),
                pregated=pregated,
                # No per-region scoring on a real photograph. FIELD_BANDS is the
                # *generator's* layout, and applying it to a photo of a real bottle
                # measures arbitrary rows and reports the result as if it meant
                # something. Real evidence regions come from the extractor, per field.
                regions_scored=False,
                blur=processed.quality_before.blur,
                exposure=processed.quality_before.exposure,
                glare=processed.quality_before.glare,
                skew_deg=processed.quality_before.skew_deg,
                note="; ".join(processed.notes),
            )
        )
    return report


