ROOT = Path(__file__).resolve().parents[1]

#: Verdicts that mean "this field was checked and it was fine".
PASSING: frozenset[Verdict] = frozenset({Verdict.MATCH, Verdict.ACCEPTABLE_VARIATION})


@dataclass
class Outcome:
    """One condition, run end to end."""

    condition: str
    tc: str
    expectation: str
    pregated: bool
    illegible: set[FieldName] = field(default_factory=set)
    verified: int = 0
    unreadable: int = 0
    blur: float = 0.0
    exposure: float = 0.0
    glare: float = 0.0
    skew_deg: float = 0.0
    note: str = ""

    @property
    def false_pass(self) -> bool:
        """Something illegible was treated as legible.

        Read per expectation, because "illegible" means a different thing in each:
        a hopeless image that slipped the gate, or a warning under glare that came back
        verified anyway.
        """
        match self.expectation:
            case "pregated":
                return not self.pregated
            case "warning_illegible":
                return FieldName.GOVERNMENT_WARNING not in self.illegible
            case _:
                return False

    @property
    def false_flag(self) -> bool:
        """Something legible was treated as illegible."""
        match self.expectation:
            case "readable":
                return self.pregated or bool(self.illegible)
            case "warning_illegible":
                return bool(self.illegible - {FieldName.GOVERNMENT_WARNING})
            case _:
                return False

    @property
    def met(self) -> bool:
        return not self.false_pass and not self.false_flag


@dataclass
class Report:
    tier: str
    outcomes: list[Outcome] = field(default_factory=list)

    @property
    def false_passes(self) -> list[Outcome]:
        return [o for o in self.outcomes if o.false_pass]

    @property
    def false_flags(self) -> list[Outcome]:
        return [o for o in self.outcomes if o.false_flag]

    @property
    def met(self) -> int:
        return sum(1 for o in self.outcomes if o.met)

    @property
    def passed(self) -> bool:
        """False passes fail the run on their own. False flags are reported, not fatal —
        a usable photo wrongly rejected is a cost, not a compliance failure."""
        return not self.false_passes


def run_condition(spec: LabelSpec, image: np.ndarray, condition: degrade.Condition) -> Outcome:
    processed = preprocess.preprocess(image)
    pregated = quality.should_skip_extraction(processed.quality_before)

    outcome = Outcome(
        condition=condition.name,
        tc=condition.tc,
        expectation=condition.expectation,
        pregated=pregated,
        blur=processed.quality_before.blur,
        exposure=processed.quality_before.exposure,
        glare=processed.quality_before.glare,
        skew_deg=processed.quality_before.skew_deg,
        note="; ".join(processed.notes),
    )
    if pregated:
        # The pre-gate's whole point: no model call, nothing verified, nothing claimed.
        return outcome

    outcome.illegible = quality.illegible_regions(processed.image, FIELD_BANDS)
    result = verify(
        Application.model_validate(spec.application()),
        [ImageInput(index=0, data=b"", role="single")],
        SpecBackedProvider(spec, illegible=outcome.illegible),
    )
    outcome.verified = sum(1 for f in result.fields if f.verdict in PASSING)
    outcome.unreadable = sum(1 for f in result.fields if f.verdict is Verdict.UNREADABLE)
    return outcome


@cache
def _degraded(name: str) -> np.ndarray:
    """The base label with one degradation applied, rendered once per process.

    Cached because the threshold sweep re-runs the whole set at every level, and
    rendering plus warping the same fixture forty times is forty times the work for
    identical pixels. Nothing here depends on a threshold — the degradations are the
    input, the thresholds only change how it is judged.
    """
    base = np.array(render(by_name(degrade.BASE_FIXTURE)))
    return next(c for c in degrade.CONDITIONS if c.name == name).apply(base)


def evaluate(conditions: list[degrade.Condition] | None = None) -> Report:
    spec = by_name(degrade.BASE_FIXTURE)
    report = Report(tier="A")
    for condition in conditions or degrade.CONDITIONS:
        report.outcomes.append(run_condition(spec, _degraded(condition.name), condition))
    return report


