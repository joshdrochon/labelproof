def render_table(report: Report) -> str:
    lines = [
        f"Robustness by condition — Tier {report.tier}",
        "=" * 96,
        "",
        f"{'condition':24s} {'tc':7s} {'expects':18s} {'blur':>5s} {'expo':>5s} "
        f"{'glare':>5s} {'skew':>6s}  result",
        "-" * 96,
    ]
    for o in report.outcomes:
        if o.false_pass:
            verdict = "FALSE PASS"
        elif o.false_flag:
            verdict = "false flag"
        elif o.unmeasured:
            verdict = "UNMEASURED"
        elif o.expectation == "unstated":
            verdict = "measured only"
        else:
            verdict = "ok"
        detail = "pre-gated" if o.pregated else f"{o.verified} verified, {o.unreadable} unreadable"
        lines.append(
            f"{o.condition:24s} {o.tc:7s} {o.expectation:18s} {o.blur:5.2f} "
            f"{o.exposure:5.2f} {o.glare:5.2f} {o.skew_deg:6.1f}  {verdict} ({detail})"
        )

    lines.append("")
    unmeasured = [o for o in report.outcomes if o.unmeasured]
    lines.append(f"Conditions meeting their stated obligation: {report.met}/{len(report.outcomes)}")
    if unmeasured:
        lines.append(
            f"Unmeasured ({len(unmeasured)}) — whole-image quality only, no evidence "
            f"regions to score against: " + ", ".join(o.condition for o in unmeasured)
        )
    lines.append(f"False passes (illegible treated as legible): {len(report.false_passes)}")
    lines.append(f"False flags (legible treated as illegible):  {len(report.false_flags)}")
    lines.append("")
    lines.append(
        "A change that reduces flags by increasing false passes is a regression, not an "
        "improvement."
    )
    if report.tier == "B":
        lines.append(
            "Tier B is never averaged with Tier A and never gates CI — small n, real "
            "optics, reported every run."
        )
    lines.append("")
    lines.append("PASS" if report.passed else "FAIL — false passes present")
    return "\n".join(lines)


def as_dict(report: Report) -> dict[str, Any]:
    return {
        "tier": report.tier,
        "conditions": [
            {
                "condition": o.condition,
                "tc": o.tc,
                "expectation": o.expectation,
                "pregated": o.pregated,
                "illegible": sorted(f.value for f in o.illegible),
                "regions_scored": o.regions_scored,
                "unmeasured": o.unmeasured,
                "verified": o.verified,
                "unreadable": o.unreadable,
                "scores": {
                    "blur": o.blur,
                    "exposure": o.exposure,
                    "glare": o.glare,
                    "skew_deg": o.skew_deg,
                },
                "false_pass": o.false_pass,
                "false_flag": o.false_flag,
                "note": o.note,
            }
            for o in report.outcomes
        ],
        "false_passes": len(report.false_passes),
        "false_flags": len(report.false_flags),
        "passed": report.passed,
    }


