DOCS_PATH = ROOT / "docs" / "robustness.md"


def render_docs(report: Report) -> str:
    """Build `docs/robustness.md` from the code and a live run.

    Generated rather than written, because a hand-written limitations list is a
    limitations list as of the day someone wrote it. A test compares the committed file
    against this output, so the honest account and the code that has to be honest cannot
    drift apart.
    """
    lines = [
        "# Image robustness: what is handled, and what is not",
        "",
        "<!-- Generated by `python -m scripts.robustness_eval --docs`. Do not edit by",
        "hand — edit `api/pipeline/limitations.py` and regenerate. A test fails if this",
        "file and that module disagree. -->",
        "",
        "The failure this product argues against is a tool that sounds certain about",
        "something it could not see. A robustness section listing only what works would be",
        "that same failure in prose, so the second column of every table below is the one",
        "worth reading.",
        "",
        "## Conditions under test",
        "",
        "Each fixture declares what the pipeline owes it. `readable` means every field",
        "still verifies. `warning_illegible` means the warning alone comes back Unreadable",
        "and the rest of the label is still checked. `pregated` means the image is hopeless:",
        "a plain-language retake reason and zero model calls.",
        "",
        "| Fixture | Case | Obligation | Current result | Why it is in the set |",
        "|---|---|---|---|---|",
    ]

    outcomes = {o.condition: o for o in report.outcomes}
    for condition in degrade.CONDITIONS:
        outcome = outcomes.get(condition.name)
        if outcome is None:
            result = "not run"
        elif outcome.false_pass:
            result = "**false pass**"
        elif outcome.false_flag:
            result = "false flag"
        elif outcome.pregated:
            result = "pre-gated, no model call"
        else:
            result = f"{outcome.verified} verified, {outcome.unreadable} unreadable"
        lines.append(
            f"| `{condition.name}` | {condition.tc} | `{condition.expectation}` | "
            f"{result} | {condition.why} |"
        )

    lines += [
        "",
        f"Currently {report.met}/{len(report.outcomes)} conditions meet their obligation, "
        f"with {len(report.false_passes)} false passes and {len(report.false_flags)} "
        f"false flags.",
        "",
    ]

    def section(items: list[Limitation]) -> list[str]:
        out: list[str] = []
        for limitation in items:
            out += [
                f"### {limitation.area}",
                "",
                f"**Handled.** {limitation.handled}",
                "",
                f"**Not handled.** {limitation.not_handled}",
                "",
                f"**Why.** {limitation.why}",
                "",
                f"*Evidence:* `{limitation.evidence}`",
                "",
            ]
        return out

    lines += [
        "## Running in the product",
        "",
        "`verify_endpoint` sanitises the upload and scores whole-image quality, so the",
        "pre-gate is live: a hopeless photograph gets a plain-language retake reason and",
        "costs nothing. Everything in this section executes on a real request.",
        "",
    ]
    lines += section([x for x in LIMITATIONS if x.runs_in_production])

    lines += [
        "## Built and tested, but NOT wired into the product",
        "",
        "**These do not execute on a request today.** `verify_endpoint` never calls",
        "`preprocess.preprocess`, `assess_region` or `illegible_regions`, so deskewing,",
        "exposure lifting, glare recovery and per-region readability run in the test suite",
        "and the harnesses and nowhere else.",
        "",
        "Concretely: an image that is sharp everywhere except a smeared warning region",
        "scores `blur=1.000, verdict='ok'` on a real request and goes to the model with no",
        "per-field caveat. The TC-12 behaviour described below is real, tested, and",
        "currently unreachable from the API.",
        "",
        "Listing them as handled would be the exact failure this document exists to",
        "prevent. The route belongs to another wave; the next section is the change.",
        "",
    ]
    lines += section([x for x in LIMITATIONS if not x.runs_in_production])

    lines += [
        "## Wiring the unwired half",
        "",
        "```",
        WIRING.strip(),
        "```",
        "",
        "## Reproducing every number here",
        "",
        "```",
        "python -m fixtures.generator.degrade      # regenerate the fixtures",
        "python -m scripts.robustness_eval         # per-condition report",
        "python -m scripts.calibrate_quality       # threshold sweep, false passes per level",
        "python -m scripts.compression_sweep       # client encode quality vs the warning",
        "python -m scripts.crop_before_send        # is label detection reliable enough",
        "```",
        "",
        "## The gap that has not been measured yet",
        "",
        "Everything above is Tier A: labels this repo generated, degraded by code this repo",
        "wrote. It proves the pipeline can read our own renderer. Tier B — real phone",
        "photographs of real bottles — is reported separately and never averaged in, because",
        "the difference between the two numbers is the honest answer to \"does this work\".",
        "",
        "Every harness above takes `--photos` and runs unchanged against that set.",
        "",
    ]
    return "\n".join(lines)


def write_docs(report: Report) -> Path:
    DOCS_PATH.parent.mkdir(parents=True, exist_ok=True)
    DOCS_PATH.write_text(render_docs(report))
    return DOCS_PATH


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--json", action="store_true", help="emit machine-readable output")
    parser.add_argument(
        "--docs", action="store_true", help="regenerate docs/robustness.md (LP-202)"
    )
    parser.add_argument(
        "--photos",
        type=Path,
        help="run Tier B against a directory of real photographs instead",
    )
    args = parser.parse_args(argv)

    if args.docs:
        report = evaluate()
        print(f"wrote {write_docs(report).relative_to(ROOT)}")
        return 0 if report.passed else 1

    if args.photos:
        if not args.photos.is_dir():
            print(f"no such directory: {args.photos}", file=sys.stderr)
            return 2
        report = evaluate_photos(args.photos)
    else:
        report = evaluate()

    print(json.dumps(as_dict(report), indent=2) if args.json else render_table(report))
    return 0 if report.passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
