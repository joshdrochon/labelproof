def test_the_golden_set_declares_its_tier(golden: dict[str, Any]) -> None:
    """Tier A (synthetic) and Tier B (photographs) are never averaged.

    A set generated by our own renderer only proves the pipeline can read our own
    renderer. Blending the two would hide the number that matters, so the file has to
    say which one it is.
    """
    assert golden["tier"] == "A"
    assert "synthetic" in golden["description"].lower()


def test_every_top_level_key_is_one_the_harness_reads(golden: dict[str, Any]) -> None:
    assert set(golden) == {"tier", "description", "fixtures", "not_generated"}


def test_every_entry_carries_the_full_set_of_keys(entries: list[dict[str, Any]]) -> None:
    """A missing key is a `KeyError` mid-eval, or worse a silent default.

    `expect` defaulting to `{}` means "everything should match", which is a real
    expectation and not one you want to acquire by omission.
    """
    required = {
        "name", "commodity", "images", "sha256", "application",
        "expect", "expect_findings", "pending", "notes",
    }
    for entry in entries:
        assert set(entry) == required, entry.get("name")


def test_every_fixture_name_is_unique(entries: list[dict[str, Any]]) -> None:
    names = [entry["name"] for entry in entries]
    assert len(names) == len(set(names))


def test_every_fixture_name_declares_its_canonical_case(
    entries: list[dict[str, Any]],
) -> None:
    """`tc03_title_case_warning` — the case is in the name, so a failure names the row.

    An eval line that reads `fixture_7 failed` sends somebody hunting; one that reads
    `tc03_title_case_warning failed` names the regulation.
    """
    for entry in entries:
        assert re.match(r"^tc\d{2}_[a-z0-9_]+$", entry["name"]), entry["name"]


