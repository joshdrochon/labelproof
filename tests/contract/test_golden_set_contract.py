"""CONTRACT: `golden/set.json` is the accuracy report's input, so its schema is load-bearing.

The golden set is what OPS-3's published accuracy number is computed from, and what
LP-290 — "zero false passes on warning violations, verified and published" — is verified
against. A typo in a verdict string, a fixture whose expectation names a field that does
not exist, or a checked-in file that has drifted from the catalog it was generated from,
all produce a *number* rather than an error. A wrong number in an accuracy report is worse
than a missing one, because somebody acts on it.

So this file treats the golden set as an external interface and validates it the way the
provider response is validated: every key present, every value in its domain, every
cross-reference resolving.

`test_the_golden_set_covers_at_least_twenty_five_labels` is `xfail(strict=True)` — the
set holds fifteen today and LP-233 asks for twenty-five. The requirement is asserted
rather than described so that reaching it turns the pin red.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

import pytest

from api.models import Application, Commodity, FieldName, Verdict
from fixtures.generator.catalog import CATALOG, NOT_GENERATED

pytestmark = pytest.mark.contract

ROOT = Path(__file__).resolve().parents[2]
GOLDEN = ROOT / "golden" / "set.json"
LABELS = ROOT / "fixtures" / "labels"

#: LP-233. Every canonical case in the PRD's table, TC-01 through TC-22.
CANONICAL_CASES = [f"TC-{n:02d}" for n in range(1, 23)]

#: LP-233's floor for the synthetic tier.
REQUIRED_LABEL_COUNT = 25


@pytest.fixture(scope="module")
def golden() -> dict[str, Any]:
    if not GOLDEN.exists():  # pragma: no cover - the file is committed
        pytest.fail("golden/set.json is missing; the eval has no input")
    loaded: dict[str, Any] = json.loads(GOLDEN.read_text())
    return loaded


@pytest.fixture(scope="module")
def entries(golden: dict[str, Any]) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = golden["fixtures"]
    return rows


