def _covered_cases(entries: list[dict[str, Any]]) -> set[str]:
    generated = {f"TC-{entry['name'][2:4]}" for entry in entries}
    return generated | set(NOT_GENERATED)


def test_every_canonical_case_is_either_generated_or_explained(
    entries: list[dict[str, Any]]
) -> None:
    """All 22 rows of the PRD's table are accounted for.

    Seven cannot be generated from a spec — an angled photograph, glare, a cat — and
    each says so by name in `NOT_GENERATED`. "Accounted for" means generated *or*
    explained; what it must never mean is absent.
    """
    missing = sorted(set(CANONICAL_CASES) - _covered_cases(entries))
    assert missing == [], f"canonical cases with no fixture and no explanation: {missing}"


def test_every_ungenerated_case_says_why(entries: list[dict[str, Any]]) -> None:
    for case, reason in NOT_GENERATED.items():
        assert case in CANONICAL_CASES, case
        assert len(reason.strip()) > 10, case


def test_no_case_is_both_generated_and_listed_as_ungenerated(
    entries: list[dict[str, Any]]
) -> None:
    """Two sources of truth for one case is one too many."""
    generated = {f"TC-{entry['name'][2:4]}" for entry in entries}
    assert generated & set(NOT_GENERATED) == set()


def test_the_warning_cases_are_all_generated(entries: list[dict[str, Any]]) -> None:
    """TC-03 through TC-07 are the warning statement, and they carry LP-290.

    "Zero false passes on warning violations" is verified against these five. A warning
    case that quietly moved into the ungenerated list would remove the evidence for the
    product's central claim.
    """
    generated = {f"TC-{entry['name'][2:4]}" for entry in entries}
    for case in ("TC-03", "TC-04", "TC-05", "TC-06", "TC-07"):
        assert case in generated, f"{case} must be a generated fixture"


