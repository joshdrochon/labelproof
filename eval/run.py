"""Evaluation harness — accuracy as a number, tracked run over run (OPS-2, OPS-3).

Runs the golden set through the real pipeline and reports:

* per-field accuracy against expected verdicts
* a verdict confusion matrix
* **false passes on warning violations** — the release-blocking gate (OPS-3)

The last one is not one metric among several. A false pass on the warning statement is
the worst failure this product can produce, so it is checked separately, reported
separately, and fails the run on its own regardless of overall accuracy.

Tier A (synthetic) and Tier B (real photographs) are reported separately and never
averaged. A set generated by our own renderer only proves the pipeline can read our own
renderer, so blending the two would hide the number that matters.

    python -m eval.run
    python -m eval.run --json
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path

from api.models import Application, FieldName, Verdict
from api.provider.base import ImageInput
from api.provider.fake import SpecBackedProvider
from api.verify import verify
from fixtures.generator.catalog import CATALOG
from fixtures.generator.spec import LabelSpec

ROOT = Path(__file__).resolve().parents[1]

#: Verdicts that mean "this field is fine". A warning fixture expected to be MISMATCH or
#: MISSING that lands on one of these is a false pass.
_PASSING: frozenset[Verdict] = frozenset({Verdict.MATCH, Verdict.NOT_APPLICABLE})

#: Field-level accuracy floor (OPS-3).
ACCURACY_FLOOR = 0.95


@dataclass
class FieldOutcome:
    fixture: str
    field: FieldName
    expected: Verdict
    actual: Verdict
    missing_findings: list[str] = field(default_factory=list)
    pending: str = ""
    """Ticket this outcome is waiting on. Reported, never counted as a failure."""

    @property
    def correct(self) -> bool:
        return self.expected is self.actual and not self.missing_findings

    @property
    def is_warning_false_pass(self) -> bool:
        """Expected a warning violation, got a pass. The release-blocking failure.

        A pending outcome is excluded — the capability provably does not exist yet, so
        it is a known gap rather than a regression. It stays in the report either way.
        """
        return (
            not self.pending
            and self.field is FieldName.GOVERNMENT_WARNING
            and self.expected not in _PASSING
            and self.actual in _PASSING
        )


@dataclass
class Report:
    tier: str
    outcomes: list[FieldOutcome] = field(default_factory=list)
    errors: list[tuple[str, str]] = field(default_factory=list)

    @property
    def scored(self) -> list[FieldOutcome]:
        """Outcomes that count toward accuracy — everything not waiting on a ticket."""
        return [o for o in self.outcomes if not o.pending]

    @property
    def pending(self) -> list[FieldOutcome]:
        return [o for o in self.outcomes if o.pending and not o.correct]

    @property
    def total(self) -> int:
        return len(self.scored)

    @property
    def correct(self) -> int:
        return sum(1 for o in self.scored if o.correct)

    @property
    def accuracy(self) -> float:
        return self.correct / self.total if self.total else 0.0

    @property
    def false_passes(self) -> list[FieldOutcome]:
        return [o for o in self.outcomes if o.is_warning_false_pass]

    @property
    def failures(self) -> list[FieldOutcome]:
        return [o for o in self.scored if not o.correct]

    def confusion(self) -> dict[tuple[str, str], int]:
        return Counter((o.expected.value, o.actual.value) for o in self.scored)

    @property
    def passed(self) -> bool:
        return (
            not self.errors
            and not self.false_passes
            and self.accuracy >= ACCURACY_FLOOR
        )


def expected_verdicts(spec: LabelSpec) -> dict[FieldName, Verdict]:
    """Expected verdict per field. Anything unlisted is expected to be clean."""
    listed = {FieldName(k): Verdict(v) for k, v in spec.expect.items()}
    return listed


def evaluate(specs: list[LabelSpec], tier: str = "A") -> Report:
    report = Report(tier=tier)

    for spec in specs:
        try:
            roles = ["front", "back"] if spec.face != "single" else ["single"]
            images = [ImageInput(index=i, data=b"", role=r) for i, r in enumerate(roles)]
            application = Application.model_validate(spec.application())
            result = verify(application, images, SpecBackedProvider(spec))
        except Exception as exc:  # noqa: BLE001 - the harness reports, never crashes
            report.errors.append((spec.name, f"{type(exc).__name__}: {exc}"))
            continue

        expected = expected_verdicts(spec)
        for field_result in result.fields:
            want = expected.get(
                field_result.field,
                # Unlisted fields are expected clean; Not applicable counts as clean.
                Verdict.NOT_APPLICABLE
                if field_result.verdict is Verdict.NOT_APPLICABLE
                else Verdict.MATCH,
            )
            wanted_codes = spec.expect_findings.get(field_result.field.value, [])
            raised = {f.code for f in field_result.findings}
            report.outcomes.append(
                FieldOutcome(
                    fixture=spec.name,
                    field=field_result.field,
                    expected=want,
                    actual=field_result.verdict,
                    missing_findings=[c for c in wanted_codes if c not in raised],
                    pending=spec.pending,
                )
            )

    return report


def render(report: Report) -> str:
    lines: list[str] = []
    lines.append(f"LabelProof eval — Tier {report.tier}")
    lines.append("=" * 56)

    if report.errors:
        lines.append("")
        lines.append(f"ERRORS ({len(report.errors)}) — fixtures that did not run:")
        for name, message in report.errors:
            lines.append(f"  {name}: {message}")

    lines.append("")
    lines.append(
        f"Field accuracy: {report.correct}/{report.total} "
        f"({report.accuracy:.1%})   floor {ACCURACY_FLOOR:.0%}"
    )

    if report.failures:
        lines.append("")
        lines.append(f"Mismatched expectations ({len(report.failures)}):")
        for o in report.failures:
            detail = (
                f"missing finding(s): {', '.join(o.missing_findings)}"
                if o.missing_findings
                else f"got {o.actual.value}"
            )
            lines.append(
                f"  {o.fixture:34s} {o.field.value:20s} "
                f"expected {o.expected.value:22s} {detail}"
            )

    if report.pending:
        lines.append("")
        lines.append(f"Pending capability ({len(report.pending)}) — not counted:")
        for o in report.pending:
            lines.append(
                f"  {o.fixture:34s} {o.field.value:20s} "
                f"expected {o.expected.value:22s} got {o.actual.value}   "
                f"waiting on {o.pending}"
            )

    lines.append("")
    lines.append("Confusion matrix (expected -> actual):")
    for (want, got), count in sorted(report.confusion().items(), key=lambda kv: -kv[1]):
        marker = "   " if want == got else " ! "
        lines.append(f" {marker}{want:22s} -> {got:22s} {count:4d}")

    lines.append("")
    if report.false_passes:
        lines.append(f"FALSE PASSES ON WARNING VIOLATIONS: {len(report.false_passes)}")
        for o in report.false_passes:
            lines.append(f"  {o.fixture}: expected {o.expected.value}, got {o.actual.value}")
        lines.append("  This gate is release-blocking regardless of overall accuracy.")
    else:
        lines.append("False passes on warning violations: 0")

    lines.append("")
    lines.append("PASS" if report.passed else "FAIL")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Run the LabelProof golden-set eval.")
    parser.add_argument("--json", action="store_true", help="emit machine-readable output")
    parser.add_argument(
        "--fixture", action="append", help="run only the named fixture(s)"
    )
    args = parser.parse_args(argv)

    specs = CATALOG
    if args.fixture:
        wanted = set(args.fixture)
        specs = [s for s in CATALOG if s.name in wanted]
        if not specs:
            print(f"no fixtures matched {sorted(wanted)}", file=sys.stderr)
            return 2

    report = evaluate(specs)

    if args.json:
        print(
            json.dumps(
                {
                    "tier": report.tier,
                    "accuracy": round(report.accuracy, 4),
                    "correct": report.correct,
                    "total": report.total,
                    "false_passes": len(report.false_passes),
                    "pending": [
                        {"fixture": o.fixture, "field": o.field.value, "ticket": o.pending}
                        for o in report.pending
                    ],
                    "errors": report.errors,
                    "failures": [
                        {
                            "fixture": o.fixture,
                            "field": o.field.value,
                            "expected": o.expected.value,
                            "actual": o.actual.value,
                        }
                        for o in report.failures
                    ],
                    "passed": report.passed,
                },
                indent=2,
            )
        )
    else:
        print(render(report))

    return 0 if report.passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
