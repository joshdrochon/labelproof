def run_tier_b(
    tier_b_set: tier_b.TierBSet, *, wanted: bool
) -> tuple[Report | None, str]:
    """Run Tier B if it was asked for and is runnable. Returns (report, note).

    Every branch that does not produce a report explains itself, and none of them is a
    failure: an empty set, a missing API key and a run that simply did not ask for Tier B
    are three different kinds of "not measured", and the report says which.
    """
    if not wanted:
        return None, ""
    if not tier_b_set.usable:
        return None, "not run — the manifest does not validate (see problems above)."
    if tier_b_set.is_empty:
        return None, "not run — there are no photographs yet."
    if not live.has_credentials():
        return None, live.NO_CREDENTIALS

    try:
        provider = live.build(Config.from_env().extraction_model)
    except ConfigError as exc:
        return None, f"SKIPPED — {exc}"

    return tier_b.evaluate(tier_b_set.labels, provider), ""


def run_sweep(
    models: list[str], specs: list[Any], *, dry_run: bool, repeat: int = 1
) -> tuple[str, int]:
    """The model-tier sweep. Returns (text to print, exit code).

    Opt-in by construction — nothing reaches here without `--model` — and every exit is
    zero. A sweep is a measurement, not a gate: it informs which tier ships, and a machine
    with no credentials has not regressed, it has simply not measured.
    """
    lines = sweep.estimate_lines(models, specs, repeat)

    if dry_run:
        lines.append("")
        lines.append("--dry-run: stopping before any live call. Nothing was spent.")
        return ascii_safe("\n".join(lines)), 0

    if not live.has_credentials():
        lines.append("")
        lines.append(live.NO_CREDENTIALS)
        return ascii_safe("\n".join(lines)), 0

    providers: dict[str, Any] = {}
    for model in models:
        try:
            providers[model] = live.build(model, timeout_ms=60_000).provider
        except ConfigError as exc:
            lines.append("")
            lines.append(f"SKIPPED — {exc}")
            return ascii_safe("\n".join(lines)), 0

    results = sweep.run(models, specs, lambda m: providers[m], repeat=repeat)
    lines.append(sweep.render(results, specs))
    return ascii_safe("\n".join(lines)), 0


def payload(
    report: Report,
    tier_b_set: tier_b.TierBSet | None = None,
    tier_b_report: Report | None = None,
    tier_b_note: str = "",
    *,
    exit_code: int | None = None,
    manifest_broken: bool = False,
) -> dict[str, Any]:
    """The machine-readable form of a report, gates included (LP-122).

    `exit_code` is the number the process will actually return. It is passed in rather
    than recomputed so the payload and the process can never disagree — they did, and CI
    branching on `== 3` read a compliance failure as a bad flag.
    """
    gates = gates_for(report)
    code = exit_code_for(gates) if exit_code is None else exit_code
    tier_b_body: dict[str, Any] | None = None
    if tier_b_set is not None:
        tier_b_body = {
            "gates_ci": tier_b.TIER_B_GATES,
            "labels_declared": len(tier_b_set.labels),
            "hand_verified": tier_b_set.hand_verified,
            "empty": tier_b_set.is_empty,
            "usable": tier_b_set.usable,
            "problems": tier_b_set.problems,
            "note": tier_b_note,
            # Labels that were attempted and failed — a live call that 400s, a file that
            # would not decode. Without this the artifact CI keeps cannot tell "six labels
            # all errored" from "Tier B never ran": both showed total 0, accuracy null.
            "errors": tier_b_report.errors if tier_b_report is not None else [],
            "ran": tier_b_report is not None,
            # Deliberately absent when nothing was measured. A null here is unmistakable;
            # a 1.0 from 0/0 is the number that would end up in a submission.
            "accuracy": (
                round(tier_b_report.accuracy, 4)
                if tier_b_report is not None and tier_b_report.total
                else None
            ),
            "total": tier_b_report.total if tier_b_report is not None else 0,
            "false_passes": (
                len(tier_b_report.false_passes) if tier_b_report is not None else 0
            ),
            "gap_pp": (
                round((report.accuracy - tier_b_report.accuracy) * 100, 2)
                if tier_b_report is not None and tier_b_report.total
                else None
            ),
        }

    return {
        "tier_b": tier_b_body,
        "gates": [g.as_dict() for g in gates],
        "exit_code": code,
        "status": "pass" if code == 0 else "fail",
        "tier_b_manifest_invalid": manifest_broken,
        "tier": report.tier,
        "subset": report.subset,
        "fixtures": report.fixtures,
        "accuracy": round(report.accuracy, 4),
        "correct": report.correct,
        "total": report.total,
        "accuracy_floor": report.floor,
        "ops3_floor": ACCURACY_FLOOR,
        "provider": report.provider,
        "warning_rows": len(report.warning_rows),
        "warning_violations": len(report.warning_violations),
        "false_passes": len(report.false_passes),
        "warning_coverage_ok": report.warning_coverage_ok,
        "pending": [
            {"fixture": o.fixture, "field": o.field.value, "ticket": o.pending}
            for o in report.pending
        ],
        "errors": report.errors,
        "failures": [
            {
                "fixture": o.fixture,
                "field": o.field.value,
                "expected": o.expected.value,
                "actual": o.actual.value,
                "missing_findings": o.missing_findings,
            }
            for o in report.failures
        ],
        "false_pass_rows": [
            {
                "fixture": o.fixture,
                "expected": o.expected.value,
                "actual": o.actual.value,
            }
            for o in report.false_passes
        ],
        # The run as a whole, not just Tier A's gates: a broken Tier B manifest with every
        # gate green used to yield {"exit_code": 2, "status": "fail", "passed": true} —
        # three signals, two of them agreeing, in one document. A CI job branching on
        # `.passed` shipped. `gates_passed` keeps the Tier A verdict available separately.
        "passed": code == 0,
        "gates_passed": report.passed,
    }


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="eval.run", description="Run the LabelProof golden-set eval."
    )
    parser.add_argument("--json", action="store_true", help="emit machine-readable output")
    parser.add_argument(
        "--fixture",
        action="append",
        help="run only the named fixture(s). Marks the run a subset — diagnostic, not a gate.",
    )
    parser.add_argument(
        "--report-json",
        metavar="PATH",
        help="also write the machine-readable payload here, for CI to keep as an artifact",
    )
    parser.add_argument(
        "--tier",
        choices=("a", "b", "all"),
        default="a",
        help=(
            "which golden set to run. 'a' (default) is the synthetic, CI-gating set. "
            "'b' is real bottle photographs — needs a live model, never gates."
        ),
    )
    parser.add_argument(
        "--model",
        action="append",
        metavar="MODEL_ID",
        help=(
            "run the model-tier sweep against these LIVE models (LP-329). Costs real "
            "money; never part of the CI run. Repeat the flag for each model. Omit to "
            "run the offline eval only."
        ),
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="with --model: print the planned calls and estimated spend, then stop.",
    )
    parser.add_argument(
        "--repeat",
        type=int,
        default=sweep.MIN_RUNS_PER_FIXTURE,
        metavar="N",
        help=(
            f"with --model: run each label N times (default {sweep.MIN_RUNS_PER_FIXTURE}). "
            f"A model's warning reading is stochastic; one pass cannot tell a reliable "
            f"model from a lucky one. Repeats do NOT substitute for a second fixture."
        ),
    )
    parser.add_argument(
        "--min-accuracy",
        type=float,
        default=ACCURACY_FLOOR,
        metavar="FLOAT",
        help=(
            f"field-accuracy threshold, 0..1 (default {ACCURACY_FLOOR}). May be raised "
            f"above the OPS-3 floor, never lowered."
        ),
    )
    return parser


def select(names: list[str] | None) -> list[Any] | None:
    """The specs to run, or None when a requested name does not exist."""
    if not names:
        return list(CATALOG)
    wanted = set(names)
    specs = [s for s in CATALOG if s.name in wanted]
    return specs or None


def survive_an_ascii_terminal() -> None:
    """Stop a stray character exiting 1 and looking like an accuracy failure.

    Minimal containers and cron run with `PYTHONIOENCODING=ascii` / `LC_ALL=C`. The report
    itself is transliterated to ASCII (`eval.report.ascii_safe`), but argparse help text
    and exception messages are not, and a UnicodeEncodeError there exits 1 — which this
    harness's own exit-code table defines as "field accuracy below the floor". A mangled
    character is a cosmetic defect; a misread exit code is a wrong decision.
    """
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is None:
            continue
        # A stream that refuses to be reconfigured (already detached, or not a TextIO)
        # is not worth failing the run over.
        with contextlib.suppress(ValueError, OSError):
            reconfigure(errors="backslashreplace")


def main(argv: list[str] | None = None) -> int:
    survive_an_ascii_terminal()
    args = build_parser().parse_args(argv)

    specs = select(args.fixture)
    if specs is None:
        print(f"no fixtures matched {sorted(set(args.fixture or []))}", file=sys.stderr)
        return EXIT_USAGE

    # The threshold ratchets one way. A gate whose bar can be lowered until it passes is
    # not a gate, and OPS-3 fixes the floor at 95% — raising it is tightening, lowering
    # it would be quietly redefining the requirement in a CI argument.
    #
    # `isfinite` first, because nan slips through both comparisons: `nan > 1.0` and
    # `nan < 0.95` are each False. It reached the report as "floor nan% BELOW FLOOR" and
    # exit 1 — a configuration typo indistinguishable from an accuracy regression.
    if not math.isfinite(args.min_accuracy) or not (
        ACCURACY_FLOOR <= args.min_accuracy <= 1.0
    ):
        print(
            f"--min-accuracy must be between {ACCURACY_FLOOR} and 1.0. "
            f"{ACCURACY_FLOOR:.0%} is the OPS-3 floor and this flag can only raise it.",
            file=sys.stderr,
        )
        return EXIT_USAGE

    # A negative repeat produced "Planned: -80 image(s) ... Estimated spend: ~$-4.11",
    # which is nonsense presented with a currency symbol.
    if args.repeat < 1:
        print(
            f"--repeat must be at least 1, got {args.repeat}. "
            f"{sweep.MIN_RUNS_PER_FIXTURE} is the default and the point below which a "
            f"model that reads a label correctly only sometimes looks reliable.",
            file=sys.stderr,
        )
        return EXIT_USAGE

    report = evaluate(specs, subset=bool(args.fixture), floor=args.min_accuracy)

    wanted = args.tier in ("b", "all")
    tier_b_set = tier_b.load()
    tier_b_report, tier_b_note = run_tier_b(tier_b_set, wanted=wanted)

    # A broken manifest is a repo defect, not a model result. It fails the run that asked
    # for Tier B; in a run that did not, it is a printed warning and nothing more.
    manifest_broken = wanted and not tier_b_set.usable

    # A gate failure always outranks a configuration error. Returning EXIT_USAGE for a bad
    # manifest while a warning false pass was also live reported a compliance failure to
    # CI as "bad flag" — and disagreed with the JSON, which still said exit_code 3. The
    # process exit and the payload are now the same number, always.
    gate_code: int = exit_code_for(gates_for(report))
    exit_code = gate_code if gate_code else (EXIT_USAGE if manifest_broken else 0)

    body = payload(
        report,
        tier_b_set,
        tier_b_report,
        tier_b_note,
        exit_code=exit_code,
        manifest_broken=manifest_broken,
    )

    # Printed before the Tier A report so the status line stays the last thing on stdout.
    # Reached only because the operator named a model: the CI command cannot get here,
    # which is what keeps the live path out of the build (LP-329).
    if args.model:
        text, sweep_code = run_sweep(
            args.model, specs, dry_run=args.dry_run, repeat=args.repeat
        )
        print(text, file=sys.stderr if args.json else sys.stdout)
        if sweep_code:
            return sweep_code

    if args.json:
        print(json.dumps(body, indent=2, sort_keys=True))
    else:
        print(render(report, tier_b_set, tier_b_report, tier_b_note))

    if args.report_json:
        artifact = Path(args.report_json)
        artifact.parent.mkdir(parents=True, exist_ok=True)
        artifact.write_text(json.dumps(body, indent=2, sort_keys=True) + "\n")
        if not args.json:
            # The status line is the last thing on stdout; keep it there.
            print(f"wrote {artifact}", file=sys.stderr)

    if manifest_broken:
        print(
            "golden/tier_b/manifest.json does not validate — see the Tier B section above."
            + (
                f" Exiting {exit_code} because a Tier A gate also failed, which outranks it."
                if gate_code
                else ""
            ),
            file=sys.stderr,
        )

    # Tier B's own results never touch this. Only Tier A's gates, and a bad manifest when
    # nothing worse happened.
    return exit_code


if __name__ == "__main__":
    raise SystemExit(main())
