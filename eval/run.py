"""Evaluation harness — accuracy as a number, tracked run over run (OPS-2, OPS-3).

Runs the golden set through the real pipeline and reports:

* per-field accuracy against expected verdicts
* a verdict confusion matrix
* **false passes on warning violations** — the release-blocking gate (OPS-3)

The last one is not one metric among several. A false pass on the government warning is
the worst failure this product can produce, so it is checked separately, reported
separately, and fails the run on its own regardless of overall accuracy — and a run that
scored no warning violations at all fails too, because a gate that checked nothing is
not a gate that passed.

Tier A (synthetic) and Tier B (real photographs) are reported separately and never
averaged. A set generated by our own renderer only proves the pipeline can read our own
renderer, so blending the two would hide the number that matters.

    python -m eval.run                      # the CI command: Tier A, all gates
    python -m eval.run --json               # machine-readable
    python -m eval.run --fixture tc03_...   # one fixture, diagnostic only

No network, no credentials, no live model: the default path runs entirely against the
offline spec-backed provider (ENG-3).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from eval.gates import EXIT_USAGE, exit_code_for, gates_for
from eval.outcomes import (
    ACCURACY_FLOOR,
    FieldOutcome,
    Report,
    evaluate,
    expected_verdicts,
)
from eval.report import render
from fixtures.generator.catalog import CATALOG

ROOT = Path(__file__).resolve().parents[1]

#: Re-exported so existing importers keep working after the module split.
__all__ = [
    "ACCURACY_FLOOR",
    "EXIT_USAGE",
    "FieldOutcome",
    "Report",
    "evaluate",
    "expected_verdicts",
    "main",
    "payload",
    "render",
]


def payload(report: Report) -> dict[str, Any]:
    """The machine-readable form of a report, gates included (LP-122)."""
    gates = gates_for(report)
    return {
        "gates": [g.as_dict() for g in gates],
        "exit_code": exit_code_for(gates),
        "status": "pass" if exit_code_for(gates) == 0 else "fail",
        "tier": report.tier,
        "subset": report.subset,
        "fixtures": report.fixtures,
        "accuracy": round(report.accuracy, 4),
        "correct": report.correct,
        "total": report.total,
        "accuracy_floor": report.floor,
        "ops3_floor": ACCURACY_FLOOR,
        "provider": report.provider,
        "warning_rows": len(report.warning_rows),
        "warning_violations": len(report.warning_violations),
        "false_passes": len(report.false_passes),
        "warning_coverage_ok": report.warning_coverage_ok,
        "pending": [
            {"fixture": o.fixture, "field": o.field.value, "ticket": o.pending}
            for o in report.pending
        ],
        "errors": report.errors,
        "failures": [
            {
                "fixture": o.fixture,
                "field": o.field.value,
                "expected": o.expected.value,
                "actual": o.actual.value,
                "missing_findings": o.missing_findings,
            }
            for o in report.failures
        ],
        "false_pass_rows": [
            {
                "fixture": o.fixture,
                "expected": o.expected.value,
                "actual": o.actual.value,
            }
            for o in report.false_passes
        ],
        "passed": report.passed,
    }


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="eval.run", description="Run the LabelProof golden-set eval."
    )
    parser.add_argument("--json", action="store_true", help="emit machine-readable output")
    parser.add_argument(
        "--fixture",
        action="append",
        help="run only the named fixture(s). Marks the run a subset — diagnostic, not a gate.",
    )
    parser.add_argument(
        "--report-json",
        metavar="PATH",
        help="also write the machine-readable payload here, for CI to keep as an artifact",
    )
    parser.add_argument(
        "--min-accuracy",
        type=float,
        default=ACCURACY_FLOOR,
        metavar="FLOAT",
        help=(
            f"field-accuracy threshold, 0..1 (default {ACCURACY_FLOOR}). May be raised "
            f"above the OPS-3 floor, never lowered."
        ),
    )
    return parser


def select(names: list[str] | None) -> list[Any] | None:
    """The specs to run, or None when a requested name does not exist."""
    if not names:
        return list(CATALOG)
    wanted = set(names)
    specs = [s for s in CATALOG if s.name in wanted]
    return specs or None


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)

    specs = select(args.fixture)
    if specs is None:
        print(f"no fixtures matched {sorted(set(args.fixture or []))}", file=sys.stderr)
        return EXIT_USAGE

    # The threshold ratchets one way. A gate whose bar can be lowered until it passes is
    # not a gate, and OPS-3 fixes the floor at 95% — raising it is tightening, lowering
    # it would be quietly redefining the requirement in a CI argument.
    if args.min_accuracy > 1.0 or args.min_accuracy < ACCURACY_FLOOR:
        print(
            f"--min-accuracy must be between {ACCURACY_FLOOR} and 1.0. "
            f"{ACCURACY_FLOOR:.0%} is the OPS-3 floor and this flag can only raise it.",
            file=sys.stderr,
        )
        return EXIT_USAGE

    report = evaluate(specs, subset=bool(args.fixture), floor=args.min_accuracy)
    body = payload(report)

    if args.json:
        print(json.dumps(body, indent=2, sort_keys=True))
    else:
        print(render(report))

    if args.report_json:
        artifact = Path(args.report_json)
        artifact.parent.mkdir(parents=True, exist_ok=True)
        artifact.write_text(json.dumps(body, indent=2, sort_keys=True) + "\n")
        if not args.json:
            # The status line is the last thing on stdout; keep it there.
            print(f"wrote {artifact}", file=sys.stderr)

    code: int = body["exit_code"]
    return code


if __name__ == "__main__":
    raise SystemExit(main())
