"""Tier B — real bottle photographs (LP-332).

Tier A is generated by our own renderer and tested against our own pipeline, which proves
the pipeline can read *our renderer*. Tier B is the set that can say something about real
labels: commercial typefaces, foil, curvature, phone-camera noise, actual specular glare.

Three rules govern it, and all three are structural rather than conventions:

**It never gates.** Small n and a live model make it flaky by nature; gating on it would
either break the build at random or, worse, pressure whoever is on the hook into weakening
the expectations. `TIER_B_GATES` is False and the exit code is computed without it.

**It is never averaged into Tier A.** Blending a 98% synthetic number with a 71% real-world
number produces a figure that describes neither, and it hides the one that matters. The
A-to-B gap is reported as its own line.

**Empty means empty.** With no photographs the harness reports no accuracy figure at all —
not 0%, and emphatically not the 100% that `0/0` invites. A section that quietly rendered
100% is exactly the number that would end up pasted into a submission.

The manifest is committed with an empty label list and a capture guide, so dropping images
into `golden/tier_b/images/` and adding rows is the only remaining step.
"""

from __future__ import annotations

import json
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from api.models import Application, Commodity, FieldName, Verdict
from api.provider.base import ExtractionProvider, ImageInput
from api.verify import verify
from eval.outcomes import FieldOutcome, Report

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "golden" / "tier_b" / "manifest.json"

#: Structural, not a setting. Tier B is reported every run and gates nothing.
TIER_B_GATES = False

#: Media types the pipeline accepts for a Tier B photograph, by extension.
_MEDIA_TYPES: dict[str, str] = {
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".png": "image/png",
    ".webp": "image/webp",
    ".heic": "image/heic",
    ".heif": "image/heic",
}

_ROLES = frozenset({"front", "back", "single"})
_GROUND_TRUTH = frozenset({"bootstrapped", "hand_verified"})


@dataclass(frozen=True)
class TierBImage:
    file: str
    role: str
    path: Path

    @property
    def media_type(self) -> str:
        return _MEDIA_TYPES.get(self.path.suffix.lower(), "application/octet-stream")


@dataclass(frozen=True)
class TierBLabel:
    """One real photographed label and the application it is verified against."""

    name: str
    commodity: Commodity
    images: tuple[TierBImage, ...]
    application: Application
    expect: dict[FieldName, Verdict]
    expect_findings: dict[str, list[str]]
    capture: dict[str, str]
    ground_truth: str
    notes: str


@dataclass
class TierBSet:
    """What the manifest declared, and everything wrong with it."""

    manifest_path: Path
    images_dir: Path
    labels: list[TierBLabel] = field(default_factory=list)
    problems: list[str] = field(default_factory=list)
    capture_guide: list[str] = field(default_factory=list)

    @property
    def is_empty(self) -> bool:
        return not self.labels

    @property
    def usable(self) -> bool:
        """A declared row with a missing file is a defect, not a photograph to skip."""
        return not self.problems

    @property
    def hand_verified(self) -> int:
        return sum(1 for label in self.labels if label.ground_truth == "hand_verified")


def _as_str_map(raw: Any) -> dict[str, str]:
    if not isinstance(raw, dict):
        return {}
    return {str(k): str(v) for k, v in raw.items()}


def _read_label(raw: Any, index: int, images_dir: Path, seen: set[str]) -> tuple[
    TierBLabel | None, list[str]
]:
    """Validate one manifest row. Returns the label, or the reasons it is unusable."""
    where = f"labels[{index}]"
    problems: list[str] = []

    if not isinstance(raw, dict):
        return None, [f"{where}: expected an object, got {type(raw).__name__}"]

    name = str(raw.get("name", "")).strip()
    if not name:
        problems.append(f"{where}: missing 'name'")
    elif name in seen:
        problems.append(f"{where}: duplicate name {name!r}")
    where = f"{name or where}"

    try:
        commodity = Commodity(raw.get("commodity", ""))
    except ValueError:
        problems.append(
            f"{where}: commodity {raw.get('commodity')!r} is not one of "
            f"{[c.value for c in Commodity]}"
        )
        commodity = Commodity.SPIRITS

    images: list[TierBImage] = []
    raw_images = raw.get("images")
    if not isinstance(raw_images, list) or not raw_images:
        problems.append(f"{where}: needs at least one entry in 'images'")
    else:
        for entry in raw_images:
            if not isinstance(entry, dict) or not entry.get("file"):
                problems.append(f"{where}: an 'images' entry has no 'file'")
                continue
            role = str(entry.get("role", "single"))
            if role not in _ROLES:
                problems.append(f"{where}: image role {role!r} is not one of {sorted(_ROLES)}")
            path = images_dir / str(entry["file"])
            if not path.is_file():
                # Declared but absent is a defect, not something to quietly skip: the row
                # would otherwise score against an image nobody has.
                problems.append(f"{where}: image {entry['file']!r} is not in {images_dir}")
                continue
            images.append(TierBImage(file=str(entry["file"]), role=role, path=path))

    application: Application | None = None
    try:
        application = Application.model_validate(raw.get("application", {}))
    except Exception as exc:  # pydantic ValidationError, reported not raised
        problems.append(f"{where}: 'application' is not a valid record — {exc}")

    expect: dict[FieldName, Verdict] = {}
    for key, value in _as_str_map(raw.get("expect")).items():
        try:
            expect[FieldName(key)] = Verdict(value)
        except ValueError:
            problems.append(f"{where}: expect {key!r} -> {value!r} is not a field/verdict pair")

    ground_truth = str(raw.get("ground_truth", "bootstrapped"))
    if ground_truth not in _GROUND_TRUTH:
        problems.append(
            f"{where}: ground_truth {ground_truth!r} is not one of {sorted(_GROUND_TRUTH)}"
        )

    if not str(raw.get("notes", "")).strip():
        problems.append(f"{where}: no notes — say why this bottle is in the set")

    if problems or application is None:
        return None, problems

    if name:
        seen.add(name)
    return (
        TierBLabel(
            name=name,
            commodity=commodity,
            images=tuple(images),
            application=application,
            expect=expect,
            expect_findings={
                str(k): [str(c) for c in v]
                for k, v in (raw.get("expect_findings") or {}).items()
            },
            capture=_as_str_map(raw.get("capture")),
            ground_truth=ground_truth,
            notes=str(raw["notes"]),
        ),
        [],
    )


def load(manifest_path: Path | None = None) -> TierBSet:
    """Read and validate the Tier B manifest. Never raises; problems are data."""
    path = manifest_path or MANIFEST
    images_dir = path.parent / "images"
    result = TierBSet(manifest_path=path, images_dir=images_dir)

    if not path.is_file():
        result.problems.append(f"no manifest at {path}")
        return result

    try:
        body = json.loads(path.read_text())
    except json.JSONDecodeError as exc:
        result.problems.append(f"{path.name} is not valid JSON — {exc}")
        return result

    if body.get("tier") != "B":
        result.problems.append(f"{path.name}: tier is {body.get('tier')!r}, expected 'B'")
    if body.get("gates_ci") is not False:
        # A manifest that claims to gate would be a quiet reversal of the one rule that
        # keeps this set honest, so it is rejected rather than obeyed.
        result.problems.append(
            f"{path.name}: gates_ci must be false. Tier B never gates CI."
        )

    result.capture_guide = [str(x) for x in body.get("capture_guide", [])]

    seen: set[str] = set()
    for index, raw in enumerate(body.get("labels", [])):
        label, problems = _read_label(raw, index, images_dir, seen)
        result.problems.extend(problems)
        if label is not None:
            result.labels.append(label)

    return result


def image_inputs(label: TierBLabel) -> list[ImageInput]:
    """Load the photographs off disk, in manifest order."""
    return [
        ImageInput(
            index=i,
            data=image.path.read_bytes(),
            media_type=image.media_type,
            role=image.role,
        )
        for i, image in enumerate(label.images)
    ]


#: Builds the extractor for one photographed label. Always live — there is no offline way
#: to read a photograph, so this is a required argument rather than a defaulted one.
TierBProviderFactory = Callable[[TierBLabel, list[ImageInput]], ExtractionProvider]


def evaluate(labels: list[TierBLabel], provider_for: TierBProviderFactory) -> Report:
    """Score Tier B. Same rules engine, same verdicts, different tier.

    `provider_for` is required rather than defaulted: there is no offline way to read a
    photograph, and a default would invite a Tier B run that silently measured nothing.
    """
    report = Report(tier="B", fixtures=len(labels), provider="live")

    for label in labels:
        try:
            images = image_inputs(label)
            result = verify(label.application, images, provider_for(label, images))
        # Broad on purpose: the harness reports a failed label, it never crashes with it.
        except Exception as exc:
            report.errors.append((label.name, f"{type(exc).__name__}: {exc}"))
            continue

        for field_result in result.fields:
            want = label.expect.get(
                field_result.field,
                Verdict.NOT_APPLICABLE
                if field_result.verdict is Verdict.NOT_APPLICABLE
                else Verdict.MATCH,
            )
            wanted = label.expect_findings.get(field_result.field.value, [])
            raised = {f.code for f in field_result.findings}
            report.outcomes.append(
                FieldOutcome(
                    fixture=label.name,
                    field=field_result.field,
                    expected=want,
                    actual=field_result.verdict,
                    missing_findings=[c for c in wanted if c not in raised],
                )
            )

    return report
